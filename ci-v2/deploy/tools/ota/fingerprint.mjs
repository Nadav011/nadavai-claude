#!/usr/bin/env node
// Native fingerprint per (app, platform): the hash of everything that changes the store shell.
// An OTA bundle is published under runtime-<fp12> and a shell only reads the manifest of its
// own baked fingerprint, so a web bundle never reaches a shell it was not built against
// (planning/native-apps-2026-11-06/PLAN.md P2/P3, section 8 item 7; OTA.md).
//
//   node scripts/native/fingerprint.mjs <app> <platform> [--json]
//   node scripts/native/fingerprint.mjs --all
//
// Inputs, per (app, platform), all read from the working tree:
//   1. every git-tracked file under the platform's native path, except Markdown and the web
//      assets `cap sync` copies in (those are the OTA payload, not the shell);
//   2. the app's Capacitor config files and the shell fields of its profile JSON;
//   3. the app's OTA public key (a new key needs a new shell);
//   4. the lockfile versions of every package with native code (@capacitor/*, @capawesome/*, …),
//      minus the other platform's Capacitor runtime;
//   5. the registry fields that shape the shell (appId, platform path).
import { createHash } from 'node:crypto';
import { existsSync, readFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
export const PLATFORMS = ['android', 'ios'];

/** Packages that carry native code. tests/integration/native-fingerprint.test.ts proves the rule covers node_modules. */
export const NATIVE_PACKAGE = /^(@capacitor\/|@capawesome\/|@capawesome-team\/|@capacitor-community\/|@capacitor-firebase\/|@capgo\/|capacitor-)/;
const OTHER_RUNTIME = { android: '@capacitor/ios', ios: '@capacitor/android' };

/** Generated by `cap sync` from the web build: the OTA payload itself, never a shell input. */
const GENERATED = [
  /(^|\/)app\/src\/main\/assets\/public\//,
  /(^|\/)app\/src\/main\/assets\/capacitor\.config\.json$/,
  /(^|\/)App\/App\/public\//,
  /(^|\/)App\/App\/capacitor\.config\.json$/,
  /(^|\/)App\/App\/config\.xml$/,
];
const isDoc = (path) => /\.md$/i.test(path);

export function isShellInput(path) {
  return !isDoc(path) && !GENERATED.some((re) => re.test(path));
}

export function loadRegistry(root = REPO_ROOT) {
  return JSON.parse(readFileSync(join(root, 'native', 'apps.json'), 'utf8'));
}

export function appEntry(registry, app, platform) {
  const entry = registry.apps[app];
  if (!entry) throw new Error(`Unknown app "${app}" (native/apps.json has: ${Object.keys(registry.apps).join(', ')})`);
  if (platform !== undefined && !entry.platforms[platform]) throw new Error(`Unknown platform "${platform}" for ${app}`);
  return entry;
}

/** Tracked files under `dir`, from git. A clean environment: a hook's GIT_DIR must not redirect it. */
export function gitTrackedFiles(root, dir) {
  const env = Object.fromEntries(Object.entries(process.env).filter(([k]) => !k.startsWith('GIT_')));
  const out = execFileSync('git', ['ls-files', '-z', '--', dir], { cwd: root, env, encoding: 'utf8' });
  return out.split('\0').filter(Boolean);
}

/** Resolved versions of the root importer's dependencies in a pnpm v9 lockfile (no YAML dependency). */
export function lockfileVersions(lockText) {
  const versions = {};
  let inImporters = false, inRoot = false, inDeps = false, current = null;
  for (const line of lockText.split('\n')) {
    if (/^\S/.test(line)) { inImporters = line.startsWith('importers:'); inRoot = false; inDeps = false; continue; }
    if (!inImporters) continue;
    if (/^ {2}\S/.test(line)) { inRoot = /^ {2}\.:\s*$/.test(line); inDeps = false; continue; }
    if (!inRoot) continue;
    if (/^ {4}\S/.test(line)) { inDeps = /^ {4}(dependencies|devDependencies|optionalDependencies):\s*$/.test(line); continue; }
    if (!inDeps) continue;
    const name = line.match(/^ {6}'?([^':]+(?::[^':]+)?)'?:\s*$/);
    if (name) { current = name[1]; continue; }
    const version = line.match(/^ {8}version:\s*(\S+)/);
    if (version && current) versions[current] = version[1].replace(/\(.*$/, '');
  }
  return versions;
}

const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex');

function configInputDigest(root, input) {
  const raw = readFileSync(join(root, input.path));
  if (!input.fields) return sha256(raw);
  const json = JSON.parse(raw.toString('utf8'));
  return sha256(JSON.stringify(input.fields.map((field) => [field, json[field] ?? null])));
}

/**
 * @param {{ app: string, platform: string, root?: string, registry?: object,
 *           listFiles?: (root: string, dir: string) => string[] }} options
 */
export function computeFingerprint({ app, platform, root = REPO_ROOT, registry = loadRegistry(root), listFiles = gitTrackedFiles }) {
  const entry = appEntry(registry, app, platform);
  const nativePath = entry.platforms[platform].path;
  const files = listFiles(root, nativePath)
    .filter(isShellInput)
    .filter((path) => existsSync(join(root, path)))
    .sort()
    .map((path) => [path, sha256(readFileSync(join(root, path)))]);
  const config = entry.configInputs.map((input) => [input.path, input.fields ?? null, configInputDigest(root, input)]);
  const publicKey = sha256(readFileSync(join(root, entry.publicKey)));
  const all = lockfileVersions(readFileSync(join(root, 'pnpm-lock.yaml'), 'utf8'));
  const packages = Object.keys(all)
    .filter((name) => NATIVE_PACKAGE.test(name) && name !== OTHER_RUNTIME[platform])
    .sort()
    .map((name) => [name, all[name]]);
  const inputs = { schema: 1, app, platform, appId: entry.appId, nativePath, files, config, publicKey, packages };
  const fingerprint = sha256(JSON.stringify(inputs));
  const fp12 = fingerprint.slice(0, 12);
  return { app, platform, fingerprint, fp12, runtime: `runtime-${fp12}`, shellPresent: files.length > 0, inputs };
}

function main(argv) {
  const registry = loadRegistry();
  if (argv[0] === '--all') {
    for (const app of Object.keys(registry.apps)) {
      for (const platform of PLATFORMS) {
        const fp = computeFingerprint({ app, platform, registry });
        console.log(`${app}\t${platform}\t${fp.runtime}\t${fp.shellPresent ? `${fp.inputs.files.length} native files` : 'NO SHELL (native path has no tracked files)'}`);
      }
    }
    return;
  }
  const [app, platform] = argv;
  if (!app || !platform) {
    console.error('usage: fingerprint.mjs <app> <android|ios> [--json] | --all');
    process.exit(2);
  }
  const fp = computeFingerprint({ app, platform, registry });
  console.log(argv.includes('--json') ? JSON.stringify(fp, null, 2) : fp.fingerprint);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main(process.argv.slice(2));
